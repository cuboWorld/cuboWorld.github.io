  const select = document.querySelector('.language-select');
  const elements = [...document.querySelectorAll('[data-i18n]')];
  const korean = Object.fromEntries(elements.map(element => [element.dataset.i18n, element.dataset.i18nAttr ? element.getAttribute(element.dataset.i18nAttr) : element.textContent]));
  function requestedLanguage() {
    const requested = new URL(location.href).searchParams.get('lang');
    return Object.hasOwn(translations, requested) ? requested : 'ko';
  }
  function setLanguage(language) {
    const messages = language === 'ko' ? korean : translations[language];
    document.documentElement.lang = language;
    select.value = language;
    for (const element of elements) {
      const value = messages[element.dataset.i18n] ?? korean[element.dataset.i18n];
      if (element.dataset.i18nAttr) element.setAttribute(element.dataset.i18nAttr, value);
      else element.textContent = value;
    }
    for (const link of document.querySelectorAll('[data-game-link], [data-home-link]')) {
      const url = new URL(link.href);
      if (language === 'ko') url.searchParams.delete('lang');
      else url.searchParams.set('lang', language);
      link.href = `${url.pathname}${url.search}${url.hash}`;
    }
    document.querySelector('.game-original-name').hidden = language === 'en';
  }
  select.addEventListener('change', () => {
    const url = new URL(location.href);
    if (select.value === 'ko') url.searchParams.delete('lang');
    else url.searchParams.set('lang', select.value);
    history.replaceState(history.state, '', url);
    setLanguage(select.value);
  });
  window.addEventListener('popstate', () => setLanguage(requestedLanguage()));
  function openPrivacyFromHash() {
    if (location.hash === '#site-privacy') document.querySelector('.site-privacy details').open = true;
  }
  document.querySelector('[data-open-privacy]').addEventListener('click', () => {
    document.querySelector('.site-privacy details').open = true;
  });
  window.addEventListener('hashchange', openPrivacyFromHash);
  openPrivacyFromHash();
  setLanguage(requestedLanguage());
